test_that("controllability, stabilizability, observability and detectability", {
  A <- diag(c(-1, 2))
  r <- ctrl_controllability(A, c(1, 0))
  expect_equal(r$rank, 1L)
  expect_false(r$controllable)
  expect_false(r$stabilizable)
  expect_equal(Re(r$uncontrollable_modes), 2)
  r2 <- ctrl_controllability(A, c(0, 1))
  expect_true(r2$stabilizable)
  expect_false(r2$controllable)
  o <- ctrl_observability(A, C = c(0, 1))
  expect_true(o$detectable)
  expect_false(o$observable)
  expect_true(ctrl_is_controllable(mass_spring()))
  expect_true(ctrl_is_observable(mass_spring()))
  expect_equal(ctrl_ctrb(mass_spring()), matrix(c(0, 1, 1, -3), 2))
  expect_equal(ctrl_obsv(mass_spring()), matrix(c(1, 0, 0, 1), 2))
})

test_that("staircase detects near-uncontrollable structure and PBH agrees", {
  set.seed(3)
  Q <- qr.Q(qr(matrix(rnorm(16), 4)))
  A <- Q %*% diag(c(-1, -2, -3, -4)) %*% t(Q)
  B <- Q %*% c(1, 1, 0, 0)
  r <- ctrl_controllability(A, B)
  expect_equal(r$rank, 2L)
  expect_equal(sort(Re(r$uncontrollable_modes)), c(-4, -3), tolerance = 1e-10)
  expect_equal(sum(!r$pbh$controllable), 2L)
})
