test_that("native entry points reject malformed direct calls", {
  ns <- asNamespace("controlcompR")
  cs <- get("cc_schur", ns)
  cq <- get("cc_qz", ns)
  ct <- get("cc_trsyl", ns)
  A <- diag(2)
  expect_error(.Call(cs, 1:4, 0L, 0), "double matrix")
  expect_error(.Call(cs, matrix(0, 2, 3), 0L, 0), "square")
  expect_error(.Call(cs, A, 5L, 0), "mode")
  expect_error(.Call(cs, A, 0L, NA_real_), "finite")
  expect_error(.Call(cq, A, diag(3), 0L, 0, c(TRUE, TRUE)), "same size")
  expect_error(.Call(cq, A, "x", 0L, 0, c(TRUE, TRUE)), "double matrix")
  expect_error(.Call(cq, A, A, 0L, 0, NA), "logical")
  expect_error(.Call(ct, A, A, matrix(0, 3, 2), "N", "N", 1L), "rows")
  expect_error(.Call(ct, A, A, A, "X", "N", 1L), "\"N\" or \"T\"")
  expect_error(.Call(ct, A, A, A, 1, "N", 1L), "single strings")
  expect_error(.Call(ct, A, A, A, "N", "N", 3L), "isgn")
})

test_that("native wrappers handle empty and integer inputs", {
  expect_equal(controlcompR:::schur_real(matrix(1L))$values, 1 + 0i)
  q <- controlcompR:::qz_real(matrix(0, 0, 0), matrix(0, 0, 0))
  expect_length(q$beta, 0)
  X <- controlcompR:::trsyl(matrix(1L), matrix(2L), matrix(3L))
  expect_equal(drop(X), 1)
})
